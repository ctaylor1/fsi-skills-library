"""Exercise attribution enforcement against messages, the index, and merged history."""

import os
import json
import pathlib
import subprocess
import tempfile
import unittest

from check_contributor_policy import violations


CHECKER = pathlib.Path(__file__).with_name('check_contributor_policy.py').resolve()


class PolicyTextTests(unittest.TestCase):
    def test_named_ai_credits(self):
        for identity in ('Claude', 'Anthropic', 'Codex', 'OpenAI', 'ChatGPT',
                         'Copilot', 'Gemini', 'Cursor', 'Windsurf', 'AI assistant', 'GPT-5'):
            with self.subTest(identity=identity):
                self.assertTrue(violations(f'# Generated by {identity}'))
                self.assertTrue(violations(f'Contributor: {identity}'))

    def test_unknown_coauthor_trailers_are_rejected(self):
        self.assertTrue(violations('Fix issue\n\nCo-Authored-By: Future Tool <tool@example.test>', message=True))

    def test_other_attribution_trailers_are_rejected(self):
        for trailer in ('Signed-off-by', 'Reviewed-by', 'Assisted-by', 'Suggested-by'):
            with self.subTest(trailer=trailer):
                self.assertTrue(violations(f'{trailer}: Codex <tool@example.test>', message=True))

    def test_multiline_credit(self):
        self.assertTrue(violations('## Contributors:\n\n- Codex'))
        self.assertTrue(violations('## Acknowledgments\n- Claude'))
        self.assertTrue(violations('Special thanks to Copilot'))
        self.assertTrue(violations('"author": "Codex"'))

    def test_decorated_footer_and_session_credit(self):
        self.assertTrue(violations('\U0001f916 Generated with [Claude Code](https://example.test)'))
        self.assertTrue(violations('<!-- Written by Codex -->'))
        self.assertTrue(violations('**Generated** by **Copilot**'))
        self.assertTrue(violations('Claude-Session: https://claude.ai/example', message=True))

    def test_tool_references_and_human_authorship_are_allowed(self):
        for text in ('Supports Claude Desktop and ChatGPT.',
                     'Run the Codex CLI to reproduce the validation.',
                     '"model_id": "claude-example"',
                     'Author: Chris Taylor',
                     'Remove AI contributor credits from history',
                     'Copyright Example Corporation. All rights reserved.'):
            with self.subTest(text=text):
                self.assertFalse(violations(text, message=True))
        self.assertFalse(violations('Author: Chris Taylor\n\nSupports AI workflows.'))


class RepositoryTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory(prefix='fsi-attribution-test-')
        self.root = pathlib.Path(self.directory.name)
        self.env = dict(os.environ)
        for key in tuple(self.env):
            if key.startswith(('GIT_',)):
                self.env.pop(key)
        self.env['GIT_CONFIG_NOSYSTEM'] = '1'
        self.env['GIT_CONFIG_GLOBAL'] = os.devnull
        self.git('init', '-q')
        self.git('config', 'user.name', 'Human Maintainer')
        self.git('config', 'user.email', 'maintainer@example.test')

    def tearDown(self):
        self.directory.cleanup()

    def git(self, *args):
        return subprocess.check_output(['git', *args], cwd=self.root, env=self.env, stderr=subprocess.PIPE).decode().strip()

    def check(self, *args, env=None):
        return subprocess.run(['python3', str(CHECKER), *args], cwd=self.root,
                              env=env or self.env, capture_output=True, text=True)

    def commit(self, message):
        self.git('commit', '--allow-empty', '-qm', message)
        return self.git('rev-parse', 'HEAD')

    def test_commit_message_and_actual_author_identity(self):
        message = self.root / 'message.txt'
        message.write_text('Improve validation\n')
        self.assertEqual(self.check('--message', str(message), '--identities').returncode, 0)
        message.write_text('Improve validation\n\nCo-Authored-By: Codex <tool@example.test>\n')
        self.assertEqual(self.check('--message', str(message)).returncode, 1)
        env = dict(self.env, GIT_AUTHOR_NAME='Future Coding Agent [bot]')
        self.assertEqual(self.check('--identities', env=env).returncode, 1)

    def test_staged_content_is_checked_even_if_working_copy_is_clean(self):
        source = self.root / 'new.py'
        source.write_text('# Generated by Claude\n')
        self.git('add', 'new.py')
        source.write_text('# Human-maintained source\n')
        result = self.check('--staged')
        self.assertEqual(result.returncode, 1)
        self.assertIn('new.py:1', result.stderr)
        self.git('add', 'new.py')
        self.assertEqual(self.check('--staged', '--tree').returncode, 0)

    def test_pull_request_body_and_edits(self):
        event = self.root / 'event.json'
        event.write_text(json.dumps({'pull_request': {'title': 'Improve validation', 'body': 'Tests pass.'}}))
        self.assertEqual(self.check('--event', str(event)).returncode, 0)
        event.write_text(json.dumps({'pull_request': {'title': 'Improve validation', 'body': '\U0001f916 Generated with Claude Code'}}))
        self.assertEqual(self.check('--event', str(event)).returncode, 1)
        event.write_text(json.dumps({'ref': 'refs/heads/main'}))
        self.assertEqual(self.check('--event', str(event)).returncode, 0)

    def test_history_rejects_ai_author(self):
        self.git('config', 'user.name', 'Codex')
        self.commit('Update source')
        self.assertEqual(self.check('--history', 'HEAD').returncode, 1)

    def test_merge_cannot_reintroduce_old_credit(self):
        self.commit('Initial source')
        original_branch = self.git('branch', '--show-current')
        self.git('checkout', '-qb', 'old-branch')
        bad = self.commit('Old change\n\nCo-Authored-By: Claude <noreply@anthropic.com>')
        self.git('checkout', '-q', original_branch)
        self.commit('Clean work')
        self.assertEqual(self.check('--history', 'HEAD').returncode, 0)
        self.git('merge', '--no-ff', '-qm', 'Merge old branch', 'old-branch')
        result = self.check('--history', 'HEAD')
        self.assertEqual(result.returncode, 1)
        self.assertIn(bad[:12], result.stderr)


if __name__ == '__main__':
    unittest.main()
